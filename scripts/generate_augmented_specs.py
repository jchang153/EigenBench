def _readme_body(constitutions: list[str]) -> str:
    n = len(constitutions)
    trained = "\n".join(f"  · {trained_nick(c)}" for c in constitutions)
    prompted = "\n".join(f"  · {prompted_nick(c)}" for c in constitutions)
    eval_runs = "\n".join(f"  · runs/augmented/{c}/" for c in constitutions)
    return f"""# Augmented Character-Train Matrix

Constitutions ({n}): `{', '.join(constitutions)}`

## Population ({2*n + 4} models per eval run)

**Trained** ({n}, LoRA on each constitution):
{trained}

**Prompted** ({n}, base + system prompt of each constitution):
{prompted}

**Other**:
  · base (no LoRA, no prompt)
  · gpt-4o, claude-4-sonnet, gemini-2.5-flash (API refs)

## Eval runs

One EigenBench run per evaluation constitution:
{eval_runs}

## Running

```bash
# local train + serial upload (preferred)
.venv/bin/python scripts/run_local_train_upload.py --group augmented --parallel 3

# or one-at-a-time
python scripts/run.py runs/augmented/{constitutions[0]}/spec.py
```

## Question this experiment answers

The original Character-Train Matrix has 11 evaluation rows × 12 columns
(11 trained + base). The prompted matrix is a parallel grid (11 evals ×
14 columns: 11 prompted + base + 3 refs). The augmented matrix unifies
them in a single run per evaluation constitution: trained and prompted
variants are co-evaluated head-to-head under the same scenarios and the
same judges, so we can directly compare on-/off-diagonal effects of
training vs. prompting without cross-run pegging artifacts.

Auto-generated by `scripts/generate_augmented_specs.py`.
"""


def main():
    if len(sys.argv) > 1:
        constitutions = sys.argv[1:]
    else:
        constitutions = list(TRAINED_ADAPTER.keys())

    for c in constitutions:
        if c not in TRAINED_ADAPTER:
            raise SystemExit(f"unknown constitution {c!r}; add an adapter to TRAINED_ADAPTER")
        if not (CONSTITUTIONS_DIR / f"oct_{c}.json").exists():
            raise SystemExit(f"missing data/constitutions/oct_{c}.json")

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    n = len(constitutions)
    print(f"constitutions: {constitutions}")
    print(f"population per eval: 2n+4 = {2*n + 4} models")
    print(f"writing {n} eval specs under {OUTPUT_DIR.relative_to(REPO_ROOT)}/")
    for c in constitutions:
        run_dir = OUTPUT_DIR / c
        run_dir.mkdir(parents=True, exist_ok=True)
        spec_path = run_dir / "spec.py"
        spec_path.write_text(generate_spec(c, constitutions))
        print(f"  · {spec_path.relative_to(REPO_ROOT)}")

    readme = OUTPUT_DIR / "README.md"
    readme.write_text(_readme_body(constitutions))
    print(f"  · {readme.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
